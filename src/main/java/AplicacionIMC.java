    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
        // 1. Leemos los datos de las cajas de texto (JTextFields)
        String nombre = jTextField1.getText();
        int edad = Integer.parseInt(jTextField2.getText());
        float peso = Float.parseFloat(jTextField3.getText());
        float estatura = Float.parseFloat(jTextField4.getText());

        // 2. Creación del objeto Paciente (Hereda de TDAIMC)
        Paciente paciente = new Paciente(nombre, edad, peso, estatura, "P-001");

        // 3. Calculamos el IMC e integramos la recursividad (Proyección a 3 meses perdiendo 1kg/mes)
        float pesoProyectado = CalculoRecursivo.proyectarPesoRecursivo(paciente.getPesoKg(), 1.0f, 3);
        float imcFuturo = pesoProyectado / (paciente.getEstaturaMetros() * paciente.getEstaturaMetros());

        // 4. Construimos el mensaje de respuesta
        String mensaje = "== RESULTADO DE IMC ==\n"
                + "Paciente: " + paciente.getNombre() + " (" + paciente.getEdad() + " años)\n"
                + "IMC Actual: " + String.format("%.2f", paciente.calcularIMC()) + " (" + paciente.interpretarIMC() + ")\n\n"
                + "--- PRORECCIÓN RECURSIVA (3 Meses) ---\n"
                + "Peso estimado: " + String.format("%.2f", pesoProyectado) + " kg\n"
                + "IMC Proyectado: " + String.format("%.2f", imcFuturo);

        // 5. Mostramos el resultado en una ventana flotante
        javax.swing.JOptionPane.showMessageDialog(this, mensaje, "Reporte de Salud", javax.swing.JOptionPane.INFORMATION_MESSAGE);

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Por favor, ingresa valores numéricos válidos en Edad, Peso y Estatura.", 
            "Error de entrada", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

